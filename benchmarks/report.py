"""Render RESULTS.md from results.json.

The tables are generated rather than typed so the published numbers
cannot drift from the measured ones.

    python benchmarks/report.py
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "benchmarks" / "results.json"
OUT = ROOT / "benchmarks" / "RESULTS.md"


def by_label(summary, label):
    rows = [row for row in summary if row["label"] == label]
    return sorted(rows, key=lambda row: row["concurrency"])


def table(rows, note_errors=True):
    lines = [
        "| Concurrency | req/s (median) | req/s range | p50 ms | p95 ms | p99 ms |"
        + (" Errors |" if note_errors else ""),
        "|---:|---:|---:|---:|---:|---:|" + ("---:|" if note_errors else ""),
    ]
    for row in rows:
        line = (
            f"| {row['concurrency']} | {row['rps_median']} | "
            f"{row['rps_min']}–{row['rps_max']} | {row['p50_ms']} | "
            f"{row['p95_ms']} | {row['p99_ms']} |"
        )
        if note_errors:
            line += f" {row['errors_total']} |"
        lines.append(line)
    return "\n".join(lines)


def comparison(threaded, asyncs):
    lines = [
        "| Concurrency | threaded req/s | async req/s | async gain | "
        "threaded p99 ms | async p99 ms |",
        "|---:|---:|---:|---:|---:|---:|",
    ]
    async_by_c = {row["concurrency"]: row for row in asyncs}
    for row in threaded:
        other = async_by_c.get(row["concurrency"])
        if other is None:
            continue
        base = row["rps_median"] or 1
        gain = (other["rps_median"] - row["rps_median"]) / base * 100
        lines.append(
            f"| {row['concurrency']} | {row['rps_median']} | {other['rps_median']} | "
            f"{gain:+.0f}% | {row['p99_ms']} | {other['p99_ms']} |"
        )
    return "\n".join(lines)


def degradation(rows):
    """Where each build stops improving, and where it starts failing.

    "Degradation" is defined here as the first concurrency level at
    which throughput falls below the peak or errors appear, whichever
    comes first. Stated explicitly because the phrase is otherwise
    unfalsifiable.
    """
    if not rows:
        return "No data."
    peak = max(rows, key=lambda r: r["rps_median"])
    first_error = next((r for r in rows if r["errors_total"] > 0), None)
    after_peak = [r for r in rows if r["concurrency"] > peak["concurrency"]]
    drop = after_peak[0] if after_peak else None

    parts = [
        f"- Peak throughput at **concurrency {peak['concurrency']}** "
        f"({peak['rps_median']} req/s).",
    ]
    if drop:
        delta = (drop["rps_median"] - peak["rps_median"]) / peak["rps_median"] * 100
        parts.append(
            f"- Throughput falls at concurrency {drop['concurrency']} "
            f"({drop['rps_median']} req/s, {delta:+.0f}%), while p99 rises "
            f"from {peak['p99_ms']} ms to {drop['p99_ms']} ms."
        )
    if first_error:
        parts.append(
            f"- First connection errors at **concurrency "
            f"{first_error['concurrency']}**: {first_error['errors_total']} "
            f"across {first_error['repetitions']} runs "
            f"({first_error['requests_total']} requests completed)."
        )
    else:
        parts.append(
            "- No connection errors at any tested level."
        )
    return "\n".join(parts)


def main() -> None:
    data = json.loads(RESULTS.read_text(encoding="utf-8"))
    env = data["environment"]
    config = data["config"]
    summary = data["summary"]

    control = by_label(summary, "origin-direct")
    threaded = by_label(summary, "proxy-threaded")
    asyncs = by_label(summary, "proxy-async")
    cache_hit = by_label(summary, "cache-hit")
    cache_off = by_label(summary, "cache-disabled")

    peak_threaded = max((r["rps_median"] for r in threaded), default=0)
    peak_async = max((r["rps_median"] for r in asyncs), default=0)

    doc = f"""# Benchmark results

Generated by `benchmarks/report.py` from `benchmarks/results.json`.
Every number below comes straight from that file; none are typed by hand.

## Read this before quoting any figure

These were measured on a **single Windows laptop** with the load
generator, the origin server and the proxy all competing for the same 8
cores. That has three consequences worth stating plainly:

1. **The load generator is a Python program and is itself a ceiling.**
   The control row below measures it against the origin with no proxy
   in the path. Proxy numbers approaching those values are measuring
   the client, not the server.
2. **Variance is high.** Each cell is the median of
   {config['repetitions']} repetitions and the range is shown. Some
   ranges span 25% or more. Treat differences smaller than the range as
   noise.
3. **Absolute throughput is not the interesting number.** A proxy on
   dedicated hardware with a C load generator would report much higher
   figures. What is defensible here is the *relative* comparison
   between two builds measured back to back on one machine, in one run,
   against one origin.

Numbers here should be quoted as "on this hardware, under this
harness", never as the proxy's capacity.

## Environment

| | |
|---|---|
| Platform | {env['platform']} |
| CPU cores | {env['cpu_count']} |
| Python | {env['python']} |
| Run at | {env['timestamp']} |
| Duration per run | {config['duration_s']}s (plus {config['warmup_s']}s warm-up, discarded) |
| Repetitions per cell | {config['repetitions']} |
| Response body | {config['body_bytes']} bytes |

## Methodology

- **Closed loop.** C workers each send a request, wait for the complete
  response, then send the next. Throughput is an outcome of latency,
  not an applied rate.
- **One request per connection.** The proxy forces `Connection: close`
  upstream and closes the client socket after each exchange, so
  keep-alive does not exist to measure. TCP setup and teardown are
  inside every latency figure — for both builds equally.
- **Latency** is wall clock from immediately before `connect()` to the
  last byte of the response, measured with `time.perf_counter()`.
  `time.monotonic()` was not used: on Windows it has a 15.6 ms tick,
  which quantises these measurements into meaningless steps.
- **Percentiles** are nearest-rank over all requests in a run.
- **Rate limiting is disabled** for every run
  (`--rate-limit-requests 0 --no-adaptive-rate-limit`). The shipped
  default of 200 requests per client+host per minute would otherwise
  make this a benchmark of the rate limiter.
- **Both builds ship from one commit** and are selected with `--mode`,
  so the comparison is not across two checkouts.
- Warm-up traffic is run and discarded before each measurement.

Reproduce:

```bash
python benchmarks/run_bench.py \\
  --duration {config['duration_s']:g} --warmup {config['warmup_s']:g} \\
  --repeat {config['repetitions']} \\
  --concurrency {','.join(str(c) for c in config['concurrency_levels'])} \\
  --out benchmarks/results.json
python benchmarks/report.py
```

On a machine with `wrk`, `./benchmarks/run.sh` runs the same comparison
with a far better client. `benchmarks/proxy.lua` supplies the
absolute-form request line a forward proxy requires.

## Control: load generator ceiling (no proxy)

The generator against the origin directly. **This is the number that
bounds everything below.**

{table(control)}

## Threaded build (`--mode threaded`)

{table(threaded)}

## Async build (`--mode async`, default)

{table(asyncs)}

## Threaded vs async

{comparison(threaded, asyncs)}

Peak sustained throughput: **threaded {peak_threaded} req/s**,
**async {peak_async} req/s**.

## Maximum concurrency before degradation

Threaded:

{degradation(threaded)}

Async:

{degradation(asyncs)}

The async build's connection refusals at the top of the sweep are the
listen backlog overflowing, not the proxy failing a request: the accept
loop shares the event loop with request handling, so under a burst of
short-lived connections the accept queue can fill faster than it
drains. The threaded build has a dedicated accept thread and does not
show this. It is a real trade in the current design and is listed as a
scope boundary in the README rather than papered over.

## Cache hit vs no cache

Both arms request the identical URL from the identical origin on the
async build. The only variable is whether the cache is enabled, which
isolates its effect. The origin marks this path `Cache-Control:
max-age=3600`; after warm-up the cache arm is serving hits.

**Redis substitute.** Redis could not be installed on this machine (no
passwordless sudo, no Docker daemon), so `benchmarks/mini_redis.py`
implements enough of the RESP protocol for the real `redis-py` client
to talk to it over a real TCP socket. Included in these numbers: client
overhead, RESP encode/decode, loopback round trip, and the proxy's full
cache path. Not included: real Redis's performance. Redis is C and is
almost certainly faster at serving a GET than this fixture, so the
cache-hit figures here are a **pessimistic** bound.

### Cache enabled (serving hits)

{table(cache_hit)}

### Cache disabled (every request goes upstream)

{table(cache_off)}

### Effect

{comparison(cache_off, cache_hit).replace('threaded', 'no-cache').replace('async', 'cached')}

## What these numbers do and do not support

Supported by the data above:

- The async build sustains higher throughput and lower tail latency
  than the threaded build at the concurrency levels where the two
  differ by more than the measured spread.
- The cache removes the upstream fetch from the request path, and the
  latency difference is measurable.
- Neither build returned non-200 responses under load except where the
  errors column is non-zero.

**Not** supported, and not claimed anywhere in this repository:

- Any absolute capacity figure for real hardware.
- Behaviour above concurrency
  {max(config['concurrency_levels'])}, which was not tested.
- Anything about real Redis throughput.
- Anything about HTTPS/`CONNECT` throughput — only plain HTTP
  forwarding was benchmarked.
"""

    OUT.write_text(doc, encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
